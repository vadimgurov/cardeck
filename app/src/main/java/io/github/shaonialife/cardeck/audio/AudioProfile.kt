package io.github.shaonialife.cardeck.audio

/** Метод кодирования полезных данных аудио: определяет, как упаковать RTP после захвата. */
enum class AudioCodec {
    /** Голый PCM (обратный порядок байтов s16), тип = 100 полос. */
    PCM,

    /** Голый кадр AAC-LC (без заголовка ADTS/AU), тип = 102 канала. */
    AAC_LC,
}

/**
 * выбираемое один раз аудиоустройство: тип потока + `audioType` + бит формата + частота дискретизации + задержка + метод кодирования.
 *
 * Зачем   нужна «шестерня» (2026-10-20 Honda HFT/Alpine 8A250-30A фактическое заключение измерений):
 * Автомобильная машина   `/info` и `audioFormats` объявляют свои соответствующие растровые изображения в файлах
 * **согласно (type, audioType)**,
 * Реальный «медиа-аудиоканал» разных автомобилей приходится на разные уровни:
 * - Audi и т. д.: `type=100 media` + PCM 48k/44.1k готовы к игре (автор открыт 17 октября 2026 г.);
 * — Эта Honda: `type=100 media` объявляет только PCM 44.1k, SETUP возвращает 200 в dataPort,
 * , но `controlPort=0`, ответ имеет только 3 поля, `sampleTime` должен течь в машине машины `/feedback`
 * всегда равен 0 (не потребляется ни одна выборка), и машина завершит всю сессию примерно через 6,5 секунд;
 * и его реальный путь к медиафайлу: **`type=102` (MainHighAudio) + `media` + AAC-LC 44.1k**
 * (`0x400000`, bit22) — именно так происходит медиа-аудио настоящего iPhone.
 *
 * Таким образом, кандидатом должно быть несколько файлов **типа перекрестного потока и перекрестного
 * кодирования**. Если файл не работает, перейдите к следующему и нажмите вывод в соответствии с машиной.
 * Постоянство   ([AudioProfileMemory]).
 */
data class AudioProfile(
    /** Исходное значение audioType (медиа/совместимость/по умолчанию...) возвращается машине в НАСТРОЙКЕ как есть. */
    val audioType: String,
    /** Биты аудиоформата (кошачья игра `AudioFormat`: PCM48k=1<<15, PCM44.1k=1<<11, AAC-LC44.1k=1<<22). */
    val formatBit: Long,
    /** Частота выборки сбора данных, соответствующая [formatBit] – `AudioSender`, должна собираться с тем же значением. */
    val sampleRate: Int,
    /** НАСТРОЙКА audioLatencyMs. */
    val latencyMs: Long,
    /** Тип потока RTP: 100 = MainAudio (канал PCM), 102 = MainHighAudio (канал AAC-LC). */
    val streamType: Long = 100L,
    /** Загрузить метод кодирования. */
    val codec: AudioCodec = AudioCodec.PCM,
) {
    /** Ключ к постоянной памяти (включая тип потока и кодировку: один и тот же аудиотип/формат совершенно разные на разных каналах). */
    val key: String get() = "$streamType|${audioType.lowercase()}|$formatBit|${codec.name}"

    /** Используйте короткие теги для журналов. */
    val label: String
        get() = "t$streamType/$audioType/0x${formatBit.toString(16)}(${sampleRate}Hz,${codec.name},$latencyMs ms)"
}
