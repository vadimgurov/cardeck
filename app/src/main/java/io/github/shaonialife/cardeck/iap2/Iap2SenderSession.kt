package io.github.shaonialife.cardeck.iap2

import io.github.shaonialife.cardeck.transport.Iap2LinkChannel
import java.io.IOException
import java.security.SecureRandom

/**
 * Сеанс управления отправителем iAP2 (персонаж iPhone): полное описание последовательности запуска Wireless CarPlay,
 * наконец анализирует точку доступа приемника и конечную точку AirPlay из 0x5703 / 0x4301 — этап 1 доставки «Go/No-Go».
 *
 * Последовательность   (см. поведение однорангового узла reference/xcertplay Iap2WirelessControlClient):
 * 0x1D00 → 0x1D01 → 0x1D02 (идентификация)
 * 0xAA00 → 0xAA01 → 0xAA02 → 0xAA03 → 0xAA05 (MFi, пропустить проверку сертификата/подписи)
 * [Аксессуары отправляют 5 кадров подписки + 0x6800 StartHID, возвращают 0x6801]
 * 0x5702 → 0x5703 (получить SSID/пароль/канал точки доступа)
 * 0x4300 → 0x4301 (получить порт AirPlay/открытый ключ/параметры беспроводной сети)
 * 0x4E0D + 0x4E0E (уведомление о доступности беспроводной сети и идентификация передачи)
 */
class Iap2SenderSession(
    private val channel: Iap2LinkChannel,
    private val log: (String) -> Unit,
    /** Настоящий MAC-адрес Bluetooth этой машины (идентификатор передачи 0x4300/0x4E0E и идентификатор, транслируемый _carplay-ctrl; настоящая машина проверит его). */
    private val bluetoothMac: String = "02:00:00:00:00:00",
    /** Локальное имя Bluetooth (информация об устройстве 0x4E09). */
    private val deviceName: String = "iPhone",
    /**
     * Перезванивается при получении 0x5703 (учетные данные точки доступа) - мастер должен сразу: привязать машину WiFi+трансляция
     * `_carplay-ctrl._tcp` (с настоящим Bluetooth MAC). Процесс реального автомобиля (Audi MIB3):
     * Автомобиль       обнаруживает услугу по Wi-Fi и приглашает `GET /ctrl-int/1/connect` на телефон,
     * **Отправляет 0x4301** только после принятия приглашения; если перед широковещательной передачей он ждет
     * 0x4301, обе стороны будут ждать взаимоблокировки.
     */
    private val onWifiCredentials: ((WifiConfiguration) -> Unit)? = null,
    /**
     * Обратный вызов, когда  0x4301 поступает после завершения фазы 1 (поздний сигнал для автомобиля открыть окно CarPlay).
     *
     * Насос поддержания активности ранее рассматривал все сообщения как тактовые импульсы и записывал только их
     * длину: фактическое измерение Audi MMI 9310 0x4301 в
     * прибыл через **2 минуты 35 секунд** после окончания Фазы 1 (только что было открыто боковое окно машины).
     * После того как нас проглотило бревно, мы
     * не инициировал соединение AirPlay. Автомобиль и машина удалили весь RFCOMM после ожидания 15 секунд, пока никто не подключится.——
     * Пользователи       видят «автоматически отключается после подключения». После получения его необходимо
     * передать главной паре конечной точки/повторной попытки горячего обновления.
     */
    private val onEndpointUpdate: ((CarPlayEndpoint) -> Unit)? = null,
    /**
     * SSID точки доступа транспортного средства, известный этому процессу (последний раунд 0x5703/0x4301 или тот,
     * который успешно подключился к сети).
     *
     * Цель      : Если вы не получите 0x5703 в этом раунде и не дождетесь 0x4301 в течение 8 секунд, **не удаляйте цепочку напрямую**——
     * Пока мобильный телефон уже подключен (или знает) к точке доступа «автомобиль-машина», можно синтезировать
     * конечную точку `airPlayPort=0`.
     * позволяет главному устройству подключиться к текущей сети и использовать mDNS/шлюз для продолжения ожидания
     * (опоздавший 0x4301 все равно будет выполнять горячее обновление конечной точки).
     * 22 октября 2026 г. Журнал Audi: мобильный телефон находится в точке доступа автомобиля со второго раунда, но
     * каждый раунд из-за «нет учетных данных».
     * совершает самоубийство раз в 8 секунд и неоднократно очищает окно приглашения со стороны автомобиля.
     */
    private val knownCarSsid: (() -> String?)? = null,
    /**
     * используется только для постоянной памяти пресс-машины MFi ([MfiLengthMemory]). ноль = только в процессе
     * Таблица памяти       (одиночный тест/чистая JVM), не влияет на процесс протокола.
     */
    private val context: android.content.Context? = null,
) {
    /** Информация принимающей стороны анализируется из 0x5703 + 0x4301. */
    data class CarPlayEndpoint(
        val ssid: String,
        val passphrase: String,
        val channel: Int,
        val securityType: Int,
        val airPlayPort: Int,
        val deviceIdentifier: String?,
        val publicKey: String?,
        val sourceVersion: String?,
        val ipAddresses: List<String>,
        /**
         * `_airplay._tcp` Содержит растровое изображение TXT (объединенные старшие 32 бита).
         *
         * Ключевой бит: бит38 `HK_PAIRING_AND_ENCRYPT` = поддерживает сопряжение/шифрование HomeKit.
         * null = неизвестно (только 0x4301, mDNS не найден) — рассматривается как «требуется сопряжение», сохраняя старое поведение.
         * Catplay использует его, чтобы отличить принимающую сторону трех эпох: до HomeKit (CarPlay 210.81, без этого бита,
         * Только           `et=NONE` сеанс обычного текста + поток экрана AES-CTR) / поддерживается, но с возможностью
         * пропуска (280 эпох) /
         * Принудительное сопряжение (современное). 19.10.2026 Audi 4xxx (4851) Неисправность подключения напрямую
         * связана с этой категорией.
         */
        val advertisedFeatures: Long? = null,
    )

    private val parser = Iap2Csm.Parser()

    /** Кадры, которые только что были проанализированы и еще не классифицированы (в порядке поступления). */
    private val receivedFrames = ArrayDeque<Iap2Csm.Frame>()

    /**
     * [expectOrNull] «Неожиданная» область временного буфера кадра, полученная во время ожидания; Отсюда [recvFrame] имеет приоритет.
     *
     * **Необходимо отделить от [receivedFrames]**: если они смешаны, то ожидаемыйИлулл заполнит нецелевые кадры обратно.
     * Его собственная очередь чтения с приоритетом в следующем раунде будет неоднократно извлекать - записывать - и
     * помещать обратно тот же кадр, чтобы сформировать активную блокировку.
     * (фактический тест 18 октября 2026 г.: 0x5000 StartNowPlayingUpdates отправляется во время периода подготовки автомобиля и машины,
     * Журналы       обновляются со скоростью ~ 1000 строк в секунду, пока не истечет время ожидания).
     */
    private val pendingFrames = ArrayDeque<Iap2Csm.Frame>()

    /** Верхний предел области временного хранения: сообщения о подписке «автомобиль-машина» могут продолжать поступать в течение длительного периода ожидания, а отсутствие верхнего предела будет занимать память. */
    private val maxPendingFrames = 256
    private var pendingOverflowLogged = false

    private val random = SecureRandom()

    /** Результат анализа 0x5703 (автомобиль должен ответить еще раз, когда он повторно отправит 0x5702 в течение периода поддержания активности). */
    @Volatile
    private var wifi: WifiConfiguration? = null

    /** 0x4301 Было ли записано исходное тело (один раз за сеанс, чтобы избежать периодического повторного выпуска и обновления экрана). */
    private var startSessionRawLogged = false

    /** Последний отпечаток конечной точки позднего прибытия 0x4301 (детали не будут повторяться, когда транспортное средство периодически повторно отправляет один и тот же контент). */
    private var lastLateStartSessionSignature: Int? = null

    /**
     * 0x1D01 Параметр 6: Список идентификаторов сообщений, которые транспортное средство заявляет «оно может отправлять».
     * использует его, чтобы определить, действительно ли придет 0x6800 (StartHID)/0x4301 — если его нет в операторе,
     * не стоит ждать вслепую:
     * Фактические измерения Audi декларируют только 0x5703/0xea03, поэтому старый процесс требует ожидания 10 секунд
     * выше 0x4301 и 2 секунды выше StartHID.
     */
    private var accessorySendIds: Set<Int> = emptySet()

    /** 0x1D01 Параметр 7: Список идентификаторов сообщений, которые, как заявляет автомобиль, «он может получить». */
    private var accessoryReceiveIds: Set<Int> = emptySet()

    /** Определяет, действительно ли кадр содержит список приема (пустой список следует отличать от «не предоставленного»). */
    private var receiveListDeclared = false

    /**
     * Определение генерации WiFi портрета автомобиля-машины  (выход [ReceiverProfile.classify] засчитывается один
     * раз при поступлении 0x1D01).
     * Распространение обмена учетными данными WiFi **просто узнайте**, не используйте «Есть ли 0x5702 в списке», чтобы напрямую судить:
     * Список Audi MMI 3315 (отправка 2 позиций/получение 5 позиций) не содержит 0x5702, но фактически полностью поддерживается
     * 0x5702→0x5703, и **для запуска сервиса AirPlay необходимо получить 0x5702**——жесткая остановка согласно списку
     * зайдет в тупик «Порт 7000 ECONNREFUSED» (определение реального журнала автомобиля 2026-10-22).
     */
    private var wifiGen: ReceiverProfile.WifiGen = ReceiverProfile.WifiGen.UNKNOWN

    /**
     * Генерация связи автомобиль-машина  (засчитывается один раз при поступлении [ReceiverProfile.linkGenerationOf], 0x1D01).
     * CLASSIC_MIB3 (реальный автомобиль Audi DELPHI) = игнорировать маркер после обнаружения;
     * EVENT_LINK (остальное/неизвестное) = эскалация согласования канала управления по пороговому значению.
     * Подробности см. в [ReceiverProfile].
     */
    var linkGeneration: ReceiverProfile.LinkGeneration = ReceiverProfile.LinkGeneration.EVENT_LINK
        private set

    /** Заявляет ли машина, что отправит определенное сообщение; null = список не предоставлен (неизвестно, ожидайте в соответствии с консервативной стратегией). */
    private fun accessoryDeclaresSend(messageId: Int): Boolean? = if (accessorySendIds.isEmpty()) null else messageId in accessorySendIds

    /** Заявляет ли машина, что может получить определенное сообщение; null = список не указан (неизвестно, продолжайте в соответствии с консервативной стратегией). */
    private fun accessoryDeclaresReceive(messageId: Int): Boolean? = if (!receiveListDeclared) null else messageId in accessoryReceiveIds

    private companion object {
        /** Окно ожидания StartHID: xcertplay его отправит (придет сразу после подписки), а DiPlay его не отправит. */
        const val HID_WAIT_NANOS = 2_000_000_000L

        /**
         * Короткие окна, такие как  и 0x4301 (тестовая платформа отвечает в течение миллисекунд, если запрос отправлен;
         * транспортные средства, которые не заявлены, пропускаются напрямую).
         * будет использовать полное окно только тогда, когда «машина автомобиля не выдает список деклараций» — от 10 до
         * 3: весь реальный автомобиль.
         * На воспитание           выделено всего несколько десятков секунд, а измеренные ответы измеряются в миллисекундах.
         */
        const val START_SESSION_WAIT_NANOS = 3_000_000_000L

        /**
         * и другие окна для 0x5703. **Коротко**: реальный тест восьмиколесного Audi MMI 3315 0x5702→0x5703 ответ
         * 122/136/166/166/198/246/266/368 мс, 1,5 с с 4-кратным запасом; для тех, кто не поддерживает старый протокол
         * Для автомобилей           (BMW iD9 вообще не выходит в ветке НОВОЕ) это время составляет всего 1,5с, что не
         * мешает доводить до ума.
         */
        const val WIFI_CONFIG_WAIT_NANOS = 1_500_000_000L

        /**
         * — окно ожидания нового протокола (без 0x5703 информация о точке доступа находится только в 0x4301).
         * Этот тип автомобиля должен сначала передать информацию о точке доступа на мобильный телефон, прежде чем
         * мобильный телефон сможет получить доступ к сети - если окно слишком короткое, это означает немедленную смерть;
         * BMW iD9 фактически измерил весь подъем за 10 секунд, что дало 8 секунд.
         */
        const val START_SESSION_WAIT_NEW_PROTOCOL_NANOS = 8_000_000_000L

        /** 0x4301 Верхняя граница исходного журнала громкости (Audi измерила 261B, полная запись; если он аномально большой, обрезается только первая часть). */
        const val START_SESSION_RAW_LOG_BYTES = 1_024

        /**
         * Известное окно повтора «тихой» передачи. Первая попытка — сохранить исходное окно (возможно, медленный поезд),
         * Но не нужно ждать 6 секунд уже однажды вышедшей из строя шестеренки - реальный отклик iPhone находится на уровне 100мс.
         */
        const val MFI_SILENT_RETRY_WINDOW_MS = 1_500L

        /** Испытательное снаряжение (длина, первое пробное окно): порядок и окно определяются в ходе двустороннего фактического тестирования DiPlay/Audi. */
        private val MFI_ATTEMPTS = listOf(32 to 3_000L, 20 to 6_000L, 16 to 3_000L)

        /** Характеристики приемника реальной серии автомобиля (подстрока имени/модели/производителя 0x1D01, сравнение в нижнем регистре). */
        private val LEGACY_RECEIVER_MARKERS = listOf("audi", "delphi", "mib", "harman", "porsche")
    }

    /** Извлеките идентификационный текст получателя из 0x1D01 (конкатенация имени/модели/производителя в нижнем регистре) – используется для выбора длины запроса MFi. */
    private fun identityText(frame: Iap2Csm.Frame): String {
        val params = Iap2Csm.parseParams(frame.body).associateBy { it.id }
        return listOfNotNull(
            params[0]?.value?.asStringOrEmpty(),
            params[1]?.value?.asStringOrEmpty(),
            params[2]?.value?.asStringOrEmpty(),
        ).joinToString(" ").lowercase()
    }

    fun run(timeoutMillis: Long = 60_000L): CarPlayEndpoint {
        val deadline = System.nanoTime() + timeoutMillis * 1_000_000L
        if (!channel.awaitReady(remainingMillis(deadline))) {
            throw IOException("Тайм-аут согласования канала iAP2")
        }
        log("iap2 link ready peerMaxControl=${channel.peerMaxControlPayload()}")

        // ----Идентификация----
        send(Iap2MessageIds.START_IDENTIFICATION)
        val identification = expect(Iap2MessageIds.IDENTIFICATION_INFORMATION, deadline)
        logIdentification(identification)
        send(Iap2MessageIds.IDENTIFICATION_ACCEPTED)
        log("iap2 tx=0x1d02 identification-accepted")

        // Анализ протокола советника (время запуска см. ниже) После завершения MFi — фактическое измерение DiPlay 11 октября 2026 г.:
        // Отправка 0xEA00 до сертификации приведет к тому, что конечный автомат испытательного стенда остановится и не
        // вернется к 0xAA01; Ауди к этому не чувствительна)

        val eaProtocols = parseEaProtocols(identification)

        // ---- MFi (пропустить проверку: 0xAA05 самостоятельно сообщает об успехе) ----
        val identityText = identityText(identification)
        val legacyCar = LEGACY_RECEIVER_MARKERS.any { identityText.contains(it) }
        if (legacyCar) {
            log(
                "iap2 идентифицирует его как серию реального автомобиля ($identityText) - MFi предпочитает 20B (реальная " +
                    "длина записи iPhone; 32B нестабильно для обработки реальных автомобилей)",
            )
        }
        send(Iap2MessageIds.MFI_REQUEST_CERTIFICATE)
        val certificate = expect(Iap2MessageIds.MFI_CERTIFICATE, deadline)
        log("iap2 rx=0xaa01 байты сертификата=${certificate.body.size} (пропустить проверку)")
        // Длина запроса выбирается в соответствии с идентификацией получателя (коррекция фактического измерения на
        // уровне байтов Audi 2026-10-11):

        //  - Серия реальных автомобилей (Audi/Delphi MIB и т. д.): **первый тест 20B**. Реальная запись iPhone (carplay-wifi-extractor
        //    клиент) и отправитель Catplay используют 20B; Audi реагирует на 20B за считанные секунды. 32B При движении первым машина
        // **полная тишина** после кадра запроса ACK (нет ACK, нет ответа, сеанс становится зомби) – сегодня несколько
        // раундов фактического тестирования,

        //    Все сеансы из 32B→20B зависают, а все сеансы из 20B→(попадание в память) подключаются за секунды.
        // - Тестовый стенд DiPlay (идентификатор Carlinkit AuthV3 EC): **принимает только точные 32B**, если длина не
        // совпадает, ссылка будет отключена.

        // Прерывания не будет, даже если нет ответа — мы не проверяем подпись (самоотчет 0xAA05), и от того, ответит ли
        // 0x5702, будет зависеть, будет ли он выпущен.

        runMfiChallenge(deadline, prefer20First = legacyCar, receiverKey = identityText)
        send(Iap2MessageIds.MFI_AUTHENTICATION_SUCCEEDED)
        log("iap2 tx=0xaa05 аутентификация прошла успешно (самосообщение)")

        // ---- Приветствие о состоянии оборудования (должно сопровождаться 0xAA05: на основании этого автомобиль
        // определяет, что аксессуар готов) ----

        sendDeviceStateGreetings()

        // ---- Сеанс советника запускается (после завершения аутентификации MFi) ----
        // Положение Audi 0x1D01 de.audi.mmicconnectdatatransfer / com.audi.cpp.eadata0/1
        // Три протокола EA; коснитесь данных, связанных с HID, через сеанс EA. Отправка до аутентификации заглушит DiPlay (см. выше).
        for ((protocolId, name) in eaProtocols) {
            sendFireAndForget(
                Iap2MessageIds.EA_OPEN_SESSION,
                // параметр 1 = имя протокола советника (строка UTF-8); при отправке номера протокола машина не вернет 0xEA03
                Iap2Csm.u8(0, protocolId) + Iap2Csm.string(1, name),
            )
            log("iap2 tx=0xea00 startEASession protocol=$protocolId name=$name")
        }
        // Статус сессии советника (0xEA03): подтверждение в коротком окне, чтобы не занимать время ожидания последующего 0x5703.
        if (eaProtocols.isNotEmpty() &&
            accessoryDeclaresSend(Iap2MessageIds.EA_SESSION_STATUS) != false
        ) {
            val status =
                expectOrNull(
                    Iap2MessageIds.EA_SESSION_STATUS,
                    wifiRescueDeadline(deadline, 500L),
                )
            if (status != null) {
                log("iap2 rx=0xea03 Сессия советника открыта (${status.body.size}B)")
            } else {
                log("iap2 0xea03 не прибыл (сеанс EA не подтвержден) – продолжить обмен WiFi")
            }
        }

        // ---- Подписка с HID: 0x6800 является необязательным шагом ----
        // xcertplay отправляет StartHID после подписки; DiPlay удаляет этот шаг (просто дождитесь 0x5702 после подписки).
        // Поэтому здесь осталось немного подождать: после получения 0x6800 он ответит 0x6801. Если он не ждет в течение
        // 2 секунд, он продолжится напрямую.

        awaitOptionalHid(deadline)

        // ----Обмен конфигурацией WiFi (два поколения протоколов)----
        // Старый протокол (0x5702 → 0x5703): запрос мобильного телефона, автомобильная машина возвращает открытый текст AP.
        // Новый протокол (0x4300 → 0x4301): **информация о AP предоставляется 0x4301** (новая версия дополнения)
        // WirelessCarPlayParams), BMW iD9 идет по этому пути.
        //
        // База распространения = [ReceiverProfile.wifiGen], **не** "объявлен ли 0x5702 в списке":
        //  - НОВОЕ (в обоих списках более 10 элементов, но по-прежнему нет 0x57xx, формы BMW iD9) → пропустить 0x5702;
        //  - LEGACY (в списке четко указано 0x5702/0x5703) → Отправить;
        //  - НЕИЗВЕСТНО (декларация скудная или отсутствует) → **также отправлено**.
        // НЕИЗВЕСТНО Фактические доказательства, которые необходимо отправить (22 октября 2026 г., бортовой журнал
        // реального автомобиля Audi MMI 3315): список подлежащих получению.

        // Всего 5 элементов, не считая 0x5702, но в тот же день и на той же машине старая версия занимает 122 ~ 368 мс
        // после отправки 0x5702.

        // Просто вернитесь к 0x5703, подключитесь к сети через 30 мс, и порт AirPlay 7000 будет подключен; нажмите
        // «Пропустить, если список не объявлен»

        // В этой версии 0x5702 не отправлялся ни разу за 4 сеанса, а сервис AirPlay на автомобиле **никогда не запускался**
        // (Все 45 подключений ECONNREFUSED, и _airplay._tcp тоже не транслирует).
        // Список представляет собой "декларацию достижимых возможностей", и неполный список не может опровергнуть "не
        // поддерживается" - кошачья игра и

        // На автомобильной стороне xcertplay 0x5702 включен в список беспроводных сетей, что указывает на то, что
        // спецификация требует указания, но на самом деле автомобиль

        // Письмо часто упускается из виду; машина подтверждает необъявленные сообщения как обычно (в журнале того же
        // дня: 0x4e0d/0x4e0b/0x4e0e три записи отсутствуют)

        // В списке транспортное средство и машина проверяются поочередно).
        val declaresReceiveWifi =
            accessoryDeclaresReceive(Iap2MessageIds.REQUEST_ACCESSORY_WIFI_CONFIGURATION)
        val declaresSendWifi = accessoryDeclaresSend(Iap2MessageIds.ACCESSORY_WIFI_CONFIGURATION)
        val legacyWifiExchange = wifiGen != ReceiverProfile.WifiGen.NEW
        if (!legacyWifiExchange) {
            log(
                "Оценка изображения автомобиля iap2 НОВИНКА (форма BMW iD9) — пропустить 0x5702, информация AP предоставлена 0x4301" +
                    "(объявление манифеста get=${declaresReceiveWifi ?: "неизвестно"} Send=${declaresSendWifi ?: "неизвестно"}）",
            )
        } else if (declaresReceiveWifi == false || declaresSendWifi == false) {
            log(
                "Манифест iap2 не объявляет 0x5702/0x5703 (receive=${declaresReceiveWifi ?: "неизвестно"} " +
                    "Send=${declaresSendWifi ?: "неизвестно"}) А вот портрет оценивается $wifiGen - всё равно 0x5702" +
                    "(Неполный список не может опровергнуть «не поддерживается»; машина обычно обрабатывает " +
                    "необъявленные сообщения как обычно)",
            )
        }
        val wifiFromExchange: WifiConfiguration? =
            if (!legacyWifiExchange) {
                null
            } else {
                send(Iap2MessageIds.REQUEST_ACCESSORY_WIFI_CONFIGURATION)
                // Сегментированное ожидание 0x5703: сначала повторно отправьте приветствие, затем повторно отправьте 0x5702 и,
                // наконец, сдайтесь и перейдите к 0x4300/0x4301.

                var wifiConfiguration =
                    expectOrNull(
                        Iap2MessageIds.ACCESSORY_WIFI_CONFIGURATION,
                        wifiRescueDeadline(deadline, 1_500L),
                    )
                if (wifiConfiguration == null) {
                    sendDeviceStateGreetings(force = true)
                    log("iap2 0x5703 1.5s еще не прибыл - повторно отправьте приветствие о состоянии устройства и продолжайте ждать.")
                    wifiConfiguration =
                        expectOrNull(
                            Iap2MessageIds.ACCESSORY_WIFI_CONFIGURATION,
                            wifiRescueDeadline(deadline, 1_300L),
                        )
                }
                if (wifiConfiguration == null) {
                    send(Iap2MessageIds.REQUEST_ACCESSORY_WIFI_CONFIGURATION)
                    log("iap2 0x5702 повторяет передачу один раз (только подтверждение связи в первый раз)")
                    wifiConfiguration =
                        expectOrNull(Iap2MessageIds.ACCESSORY_WIFI_CONFIGURATION, deadline)
                }
                if (wifiConfiguration == null) {
                    log(
                        "iap2 0x5703 не прибыл после трех этапов спасения (приветствие/повторная передача 0x5702) - " +
                            "изменить на 0x4300/0x4301 (новая версия протокола поставляется с информацией AP)",
                    )
                    null
                } else {
                    // Явное утверждение: приведенный выше раздел ожидает присвоения три раза, чтобы не полагаться на
                    // интеллектуальное преобразование var.

                    val parsed = parseWifiConfiguration(wifiConfiguration!!)
                    log(
                        "iap2 rx=0x5703 ssid=${parsed.ssid} channel=${parsed.channel} " +
                            "security=${parsed.securityType} psk=${if (parsed.passphrase.isEmpty()) "(пустой)" else "***"}",
                    )
                    // Реальное противоядие от тупиковой ситуации в автомобиле (доказательство «кошачьей игры» CarPlayInviter):
                    // автомобиль обнаруживает пароль телефона в сети Wi-Fi.

                    // _carplay-ctrl._tcp, а затем активно отправить приглашение GET /ctrl-int/1/connect. **0x4301** будет отправлено
                    // только после успешного приглашения.

                    // Таким образом, мастер должен быть немедленно уведомлен о необходимости привязки Wi-Fi + широковещательного
                    // управления (с реальным MAC-адресом Bluetooth в качестве идентификатора TXT).

                    onWifiCredentials?.invoke(parsed)
                    parsed
                }
            }

        // ----Приветствие о состоянии устройства (0x4E0D/0x4E0A/0x4E09/0x4E0B → 0x4300)----
        // Фактическое измерение Audi MIB3: если этот пакет сообщений отсутствует, автомобиль возвращает ссылку ACK
        // только на 0x4300, но не на 0x4301.

        // Идемпотент: 0x5703 мог быть отправлен заранее во время периода ожидания (см. wifiRescueDeadline).
        sendDeviceStateGreetings()

        // ---- Сеанс CarPlay начался ----
        // Две одноранговые формы:
        // - Тестовый стенд DiPlay/некоторые производители автомобилей: получите 0x4300 и верните 0x4301 (включая порт
        // AirPlay/IP/открытый ключ)

        // - Audi MIB3: в списке распознавания указано только, что отправлен 0x5703/0xea03, **не распознается 0x4300 и не
        // отправляется 0x4301**;

        //    Конечная точка AirPlay подключается к mDNS через Wi-Fi (_airplay._tcp). Поэтому 0x4301 дает только короткие окна.
        //    Timeout возвращает CarPlayEndpoint без конечной точки, синтезированный главным mDNS.
        // 0x4300 также отправил его и проигнорировал: 2026-10-11 12:52 Реальная тестовая машина перестала его подтверждать.
        // (Наводнение канала SYN вывело его из строя), и сторожевой таймер снова чуть не покончил жизнь самоубийством.
        sendFireAndForget(
            Iap2MessageIds.CARPLAY_AVAILABILITY,
            Iap2Csm.group(1, Iap2Csm.u8(0, 1), Iap2Csm.string(1, bluetoothMac)),
        )
        // Если в декларации автомобиля нет 0x4301, то ожидание будет пропущено (Audi реально замеряла ожидание по 10
        // секунд напрасно для каждого круга):

        // Настоящий iPhone тоже не ждет такого типа автомобиля — конечная точка AirPlay синтезируется через mDNS/шлюз.
        val declaresStartSession = accessoryDeclaresSend(Iap2MessageIds.CARPLAY_START_SESSION)
        // Если у вас нет 0x5703 (машина с новым протоколом), 0x4301 является **единственным** источником информации AP - окна достаточно;
        // Есть действительно старые протокольные машины с 0x5703, которые поддерживают короткое окно в 3 секунды
        // (отклики на уровне миллисекунд).

        val startSessionWindow =
            if (wifiFromExchange == null) START_SESSION_WAIT_NEW_PROTOCOL_NANOS else START_SESSION_WAIT_NANOS
        var startSession: Iap2Csm.Frame? = null
        if (declaresStartSession == false) {
            log("Автомобиль iap2 не заявляет, что отправит 0x4301 — пропустите ожидание (конечная точка AirPlay проходит через mDNS/шлюз)")
        } else {
            // Машина может отправлять только 0x4301, но не отвечать на 0x5702 вообще: подождите один раунд после отправки.
            // Если 0x4301 прибудет первым в течение этого периода (обычная последовательность нового протокола), он будет принят напрямую.
            startSession =
                expectOrNull(
                    Iap2MessageIds.CARPLAY_START_SESSION,
                    minOf(deadline, System.nanoTime() + startSessionWindow),
                )
        }
        val endpoint =
            if (startSession != null) {
                parseStartSession(startSession, wifiFromExchange)
            } else {
                // Нельзя сказать, что «эта машина не будет отправлена»: Audi MMI 9310 заявила, что будет отправлена, и она
                // действительно отправлена, но уже с опозданием.

                // 2 минуты 35 секунд (журнал 18 октября 2026 г.). В формулировке должно сохраняться предположение, что
                // «переиздание может произойти позже».

                // В противном случае это предложение введет вас в заблуждение, заставив вас думать, что «эта дорога недоступна
                // для этого транспортного средства» во время расследования.

                log(
                    if (declaresStartSession == true) {
                        "iap2 0x4301 не прибыл в окно ${startSessionWindow / 1_000_000_000}s" +
                            "(автомобиль заявил 0x4301 — он может прийти позже и перезапустить сопряжение) —" +
                            "Сначала используйте mDNS/шлюз"
                    } else {
                        "iap2 0x4301 не пришел (машина не объявила, что будет отправлена, конечная точка AirPlay " +
                            "использует mDNS _airplay._tcp)"
                    },
                )
                if (wifiFromExchange != null) {
                    // Учетные данные для 0x5703 есть, но 0x4301 не пришел: конечная точка передана на синтез mDNS/шлюза.
                    CarPlayEndpoint(
                        ssid = wifiFromExchange.ssid,
                        passphrase = wifiFromExchange.passphrase,
                        channel = wifiFromExchange.channel,
                        securityType = wifiFromExchange.securityType,
                        airPlayPort = 0,
                        deviceIdentifier = null,
                        publicKey = null,
                        sourceVersion = null,
                        ipAddresses = emptyList(),
                    )
                } else {
                    // Нет 0x5703. Три уровня защиты, первые два уровня не снимают цепочку:
                    // ① Известные точки доступа (получены в последнем раунде/уже подключены к Интернету, Audi 22 октября 2026 г.:
                    // мобильный телефон доступен со второго раунда)

                    // В точке доступа «автомобиль-машина» пустая конечная точка приведет к тому, что основной контроль будет передан
                    // на mDNS/шлюз, 0x4301 опаздывает и все еще готов к обновлению)

                    val fallback = credentiallessEndpoint(knownCarSsid?.invoke())
                    if (fallback != null) {
                        log(
                            "iap2 Нет новых учетных данных — продолжайте использовать известную точку доступа \"${fallback.ssid}\"" +
                                "(После привязки к текущей сети используйте mDNS/шлюз. Позднее прибытие 0x4301 обновит " +
                                "конечную точку в горячем режиме), не разрывая связь.",
                        )
                        fallback
                    } else if (declaresStartSession == true) {
                        // ② Автомобили с новым протоколом (GM/Cinemo, брат BMW iD9: нет 0x5702/0x5703, информация AP только в
                        // 0x4301) Оператор будет отправлен, но не в окне. Фактические измерения Cadillac CT5 (журнал 21 октября 2026
                        // г.):

                        // Окно 8S совершенно пустое и машина всегда молчит в течение 6 циклов после снятия цепи; но настоящий iPhone все
                        // равно может работать, даже если точка доступа забыта.

                        // Беспроводное соединение — автомобиль отправит 0x4301 (учетные данные, переданные через Bluetooth), но он будет
                        // отправлен с опозданием или в ожидании выполнения необходимых условий.

                        //    Audi MMI 9310 Прецедент: Выдается через 2 минуты 35 секунд после окончания этапа 1. **Цепь не снимать**:
                        // Возвращаясь к пустой конечной точке, основной элемент управления переходит в состояние ожидания; позднее
                        // поступление 0x4301 обрабатывается насосом поддержания активности

                        //    handleLateStartSession → onEndpointUpdate повторно запускает сопряжение.
                        log(
                            "iap2 0x4301 не прибыл в окно, но декларация транспортного средства и машины будет " +
                                "отправлена - не разрывайте ссылку, верните пустую конечную точку и введите Keep-Alive;" +
                                "Позднее прибытие 0x4301 повторно запустит сопряжение (прецедент Audi MMI 9310: 2 минуты 35 секунд)",
                        )
                        CarPlayEndpoint(
                            ssid = "",
                            passphrase = "",
                            channel = 0,
                            securityType = 0,
                            airPlayPort = 0,
                            deviceIdentifier = null,
                            publicKey = null,
                            sourceVersion = null,
                            ipAddresses = emptyList(),
                        )
                    } else {
                        // ③ Никакой подсказки нет вообще (SSID даже не знаю, да и машина не обещает), а если продолжать ждать, то она
                        // просто будет простаивать.

                        throw IOException(
                            "Не удалось получить учетные данные автомобильной точки доступа: для этого раунда " +
                                "0x5702/0x4301 не было предоставлено никакой информации о точке доступа." +
                                "И в этом процессе нет известной точки доступа «автомобиль-машина» (сначала повторно " +
                                "выберите машину в автомобиле-машине)",
                        )
                    }
                }
            }
        if (startSession != null) {
            logStartSessionRaw(startSession)
            log(
                "iap2 rx=0x4301 airPlayPort=${endpoint.airPlayPort} " +
                    "device=${endpoint.deviceIdentifier} publicKey=${endpoint.publicKey?.take(16)}… " +
                    "srcvers=${endpoint.sourceVersion} ips=${endpoint.ipAddresses}",
            )
        }

        // Реальная последовательность машины: 0x4301, а затем 0x4E0E (подтверждение идентификации передачи).
        // Фактическое измерение Audi: автомобиль **принимает сообщение, но никогда не подтверждает** (остальное включает
        // подтверждение миллисекундного уровня) — оно должно быть отправлено и проигнорировано.

        // В противном случае сторожевой таймер повторной передачи уничтожит весь канал Bluetooth за +20 с (при этом
        // сеанс EA/носитель касания будет потерян).

        sendFireAndForget(
            Iap2MessageIds.DEVICE_TRANSPORT_IDENTIFIER,
            Iap2Csm.string(0, bluetoothMac),
        )
        log("iap2 0x4e0d/0x4e0e/0x4300 — этап 1 завершен: получены учетные данные точки доступа и (возможно) конечная точка AirPlay")

        // Последующие действия (этап 2): присоединение к точке доступа → разрешение mDNS _airplay._tcp → основной сеанс AirPlay.
        // При отсутствии 0x5703 информация AP поступает от 0x4301 (включена в конечную точку) - автомобиль
        // переоформляется в течение гарантийного срока.

        // 0x5703/0x4301 необходимо анализировать с его помощью и нельзя оставлять пустым.
        // Пустая конечная точка (объявленная для отправки 0x4301, но не внутри окна) должна поддерживать wifi=null: в
        // противном случае период поддержания активности

        // `ap = wifi ?: fromSession` parseStartSession перезапишет опоздавший 0x4301 пустыми учетными данными.
        // Встроенная информация о точке доступа исключает единственный источник учетных данных.
        if (endpoint.ssid.isNotEmpty()) {
            this.wifi =
                wifiFromExchange ?: WifiConfiguration(
                    ssid = endpoint.ssid,
                    passphrase = endpoint.passphrase,
                    channel = endpoint.channel,
                    securityType = endpoint.securityType,
                )
        }
        return endpoint
    }

    /**
     * Переход фазы 2: после завершения вызова оставьте ссылку открытой и продолжайте записывать управляющие
     * сообщения, отправляемые аксессуаром.
     * (например, 0x5703, повторно передаваемый после 0x4E0E, запроса местоположения 0xFFFA и т. д.), пока соединение не будет разорвано.
     * Этот канал управления в истинно беспроводной CarPlay       сосуществует с сеансом AirPlay на протяжении всего
     * жизненного цикла соединения.
     */
    fun pumpIncomingForever() {
        log("СЕССИЯ продолжает работать (ссылка остается открытой, а дополнительные сообщения продолжают записываться)")
        // Потоковая передача ограничена, если один и тот же идентификатор сообщения поступает постоянно: после того, как
        // автомобиль перейдет к воспроизведению мультимедиа, он будет периодически отправлять обновления NowPlaying.

        // Регистрация поэлементно приведет к перегрузке файлового журнала (удаление файла, если его размер превышает 2
        // МБ, эквивалентно потере действительно полезного контекста).

        var lastLoggedId = -1
        var repeatCount = 0
        while (true) {
            val frame = recvFrame(30_000L)
            if (frame == null) {
                if (!channel.isAlive) break
                continue
            }
            // Сообщения жизненного цикла должны быть обработаны до ограничения тока журнала: 0x4301 может использоваться как
            // «Автомобиль только что включил CarPlay».

            // Запоздалый сигнал «окна» поступает после фазы 1. Если вы следуете логике ограничения тока, он либо будет рассматриваться как
            // Keep-Alive запоминает только длину или продолжается, потому что он имеет тот же идентификатор, что и предыдущий - оба равны
            // Отброшено (18 октября 2026 г. Основная причина Audi MMI 9310 "автоматическое отключение через 15 секунд после подключения").
            if (frame.messageId == Iap2MessageIds.CARPLAY_START_SESSION) {
                handleLateStartSession(frame)
            }
            if (frame.messageId == lastLoggedId) {
                repeatCount++
                if (repeatCount % 100 != 0) continue
            } else {
                if (repeatCount >= 99) {
                    log(
                        "iap2 Предыдущая статья 0x${lastLoggedId.toString(16)} повторил ${repeatCount + 1} раз (один и " +
                            "тот же тип ограничен)",
                    )
                }
                lastLoggedId = frame.messageId
                repeatCount = 0
            }
            log(
                "iap2 rx=0x${frame.messageId.toString(16).padStart(4, '0')} " +
                    "(${Iap2MessageIds.nameOf(frame.messageId)}) keep-alive bytes=${frame.body.size}",
            )
        }
        log("SESSION Keep Alive завершен (ссылка отключена)")
    }

    /**
     * , полученный в течение периода поддержания активности: 0x4301 анализируется в конечной точке и передается
     * ведущему устройству (горячее обновление в окне сопряжения или перезапуск после сбоя предыдущего раунда).
     * Когда       не имеет кэша 0x5703 (новый протокол автомобиля: BMW iD9 имеет только 0x4301), информация AP
     * получается напрямую из 0x4301.
     * Беспроводной групповой анализ       — это единственный источник учетных данных для данного типа автомобиля.
     * Его нельзя «игнорировать без 0x5703», как старый код.
     */
    private fun handleLateStartSession(frame: Iap2Csm.Frame) {
        logStartSessionRaw(frame)
        val endpoint = parseStartSession(frame, wifi)
        if (wifi == null && endpoint.ssid.isNotEmpty()) {
            wifi =
                WifiConfiguration(
                    ssid = endpoint.ssid,
                    passphrase = endpoint.passphrase,
                    channel = endpoint.channel,
                    securityType = endpoint.securityType,
                )
            log(
                "iap2 0x4301 поставляется с информацией о точке доступа: ssid=${endpoint.ssid} — кэшируется для " +
                    "последующего повторного использования 0x5703/0x4301.",
            )
        }
        if (endpoint.ssid.isEmpty()) {
            log("iap2 rx=0x4301 (позднее прибытие) — SSID не разрешен в беспроводной группе, эта статья игнорируется")
            return
        }
        // Транспортное средство может периодически повторно отправлять один и тот же 0x4301: подробности отображаются
        // только при изменении конечной точки, чтобы избежать очистки журнала.

        if (endpoint.hashCode() != lastLateStartSessionSignature) {
            lastLateStartSessionSignature = endpoint.hashCode()
            log(
                "iap2 rx=0x4301 (позднее прибытие, после фазы 1) airPlayPort=${endpoint.airPlayPort}" +
                    "device=${endpoint.deviceIdentifier} publicKey=${endpoint.publicKey?.take(16)}… " +
                    "srcvers=${endpoint.sourceVersion} ips=${endpoint.ipAddresses}" +
                    "—— Оставьте это на усмотрение главной конечной точки горячего обновления и повторной попытки.",
            )
        }
        onEndpointUpdate?.invoke(endpoint)
    }

    /** Примитив 0x4301 запоминается только один раз: различия в полях конечной точки между транспортными средствами (с IPv4/портом/открытым ключом или без него) могут быть определены только с его помощью. */
    private fun logStartSessionRaw(frame: Iap2Csm.Frame) {
        if (startSessionRawLogged) return
        startSessionRawLogged = true
        val body = frame.body
        val shown = if (body.size <= START_SESSION_RAW_LOG_BYTES) body else body.copyOf(START_SESSION_RAW_LOG_BYTES)
        val truncated = if (body.size > shown.size) "(первые байты ${shown.size}/${body.size})" else ""
        log("iap2 0x4301 оригинальный корпус $truncated=" + shown.joinToString("") { "%02x".format(it) })
    }

    // ---- Отправка и получение кадров ----

    /**
     * Ответ на запрос  MFi: попробуйте последовательно в соответствии с «длиной, приемлемой для узла», и переходите
     * на следующий уровень каждый раз, когда происходит сбой (0xAA04/таймаут молчания/неработающее соединение).
     * Базовая последовательность и окно       определяются фактическими измерениями на обоих концах (10 сентября 2026 г., оба обязательны):
     * - **сначала 32B**: испытательный стенд DiPlay (идентификатор Carlinkit AuthV3 EC) **принимает только точные 32B**,
     * Если длина       неверна, ссылка будет отключена напрямую (ссылка отключается в течение 70–350 мс в
     * соответствии с фактическими измерениями); его реакция быстрая (~ 0,2 с), а окна в 3 с достаточно.
     * - **20B секунд**: Реальный автомобиль Audi MIB3 отвечает на 20B в секундах (кошачья игра/экстрактор реального
     * автомобиля записан той же модели);
     * сделал две вещи, чтобы справиться с 32B: молча отключился в 10-09 и отключился в 10-11.
     * - **Итог 16B**: Некоторые старые аксессуары.
     *
     * Последовательность      *** основана на постоянной памяти автомобиля** ([MfiLengthMemory], базовая линия
     * используется только для холодного запуска и снизу вверх):
     * 19 октября 2026 г. Audi MMI 3315 фактическое измерение 20B тишина в течение 6 секунд, 32B ответ 0,64 секунды —
     * полагайтесь только на базовый уровень
     * "Настоящие автомобили имеют приоритет 20B" При каждом подключении я зря жду 6 секунд. После попадания в память
     * на первое место ставится продолжительность последнего успеха.
     * Если у       нет ответа, он вернется напрямую, не выдавая исключения — мы пропускаем проверку подписи и
     * определяем, получит ли ответ последующий 0x5702.
     * определяет, разрешено ли одноранговому узлу пройти (0xaa05 все еще может продвигаться вперед после отсутствия
     * ответа в реальном тесте реального автомобиля).
     */
    private fun runMfiChallenge(
        deadline: Long,
        prefer20First: Boolean = false,
        receiverKey: String,
    ) {
        val baselineLengths =
            if (prefer20First) {
                listOf(MFI_ATTEMPTS[1].first, MFI_ATTEMPTS[0].first, MFI_ATTEMPTS[2].first)
            } else {
                MFI_ATTEMPTS.map { it.first }
            }
        val windowOf = MFI_ATTEMPTS.associate { it.first to it.second }
        val memory = MfiLengthMemory.load(context, receiverKey)
        val order = MfiLengthMemory.orderAttempts(baselineLengths, memory)
        if (!memory.isEmpty) {
            log(
                "Память автомобильного пресса iap2 MFi ($receiverKey): ${MfiLengthMemory.describe(memory)}" +
                    " → Порядок этого раунда ${order.joinToString("/")}B",
            )
        }
        for ((position, size) in order.withIndex()) {
            // Известное «тихое» окно сокращения ларька: оно уже однажды вышло из строя, ждать, пока оно снова заполнится, не нужно.
            val baseWindow = windowOf[size] ?: MFI_ATTEMPTS.last().second
            val windowMillis =
                if (size in memory.silent && size != memory.succeeded) {
                    minOf(baseWindow, MFI_SILENT_RETRY_WINDOW_MS)
                } else {
                    baseWindow
                }
            val challenge = ByteArray(size).also(random::nextBytes)
            send(Iap2MessageIds.MFI_REQUEST_CHALLENGE, Iap2Csm.param(0, challenge))
            log("iap2 tx=0xaa02 Challenge=${size}B (время ${position + 1}, окно ${windowMillis}ms)")
            val window = minOf(System.nanoTime() + windowMillis * 1_000_000L, deadline)
            var gotResponse = false
            var gotFailure = false
            while (true) {
                val remaining = (window - System.nanoTime()) / 1_000_000L
                if (remaining <= 0) break
                val frame = recvFrame(remaining)
                if (frame == null) {
                    if (!channel.isAlive) {
                        log(
                            "Ссылка отключена во время вызова iap2 MFi (${size}B, партнер не принимает эту длину) - " +
                                "записано в отклоненной передаче автомобиля",
                        )
                        // Жесткое отклонение: доказательства на уровне канала, отменяющие память о «этой длине = последний успех» (во
                        // избежание неправильного запоминания блокировки)

                        MfiLengthMemory.recordHardRejected(context, receiverKey, size)
                        return
                    }
                    continue
                }
                when (frame.messageId) {
                    Iap2MessageIds.MFI_RESPONSE -> {
                        log("iap2 rx=0xaa03 байты подписи=${frame.body.size} (пропустить проверку)")
                        gotResponse = true
                    }

                    Iap2MessageIds.MFI_AUTHENTICATION_FAILED -> {
                        log("iap2 rx=0xaa04 вызов ${size}B отклонен")
                        gotFailure = true
                    }

                    else ->
                        log(
                            "iap2 rx=0x${frame.messageId.toString(16).padStart(4, '0')} " +
                                "(${Iap2MessageIds.nameOf(frame.messageId)})",
                        )
                }
                if (gotResponse || gotFailure) break
            }
            if (gotResponse) {
                MfiLengthMemory.recordSuccess(context, receiverKey, size)
                return
            }
            if (gotFailure) {
                MfiLengthMemory.recordRejected(context, receiverKey, size)
            } else {
                MfiLengthMemory.recordSilent(context, receiverKey, size)
            }
            if (position < order.size - 1) {
                log("iap2 MFi ${size}B нет ответа, попробуйте еще раз с ${order[position + 1]}B")
            } else {
                log(
                    "На все запросы iap2 MFi нет ответа — пропустите проверку и отправьте 0xaa05 напрямую (0x5702 " +
                        "используется для определения того, разрешен ли проезд транспортному средству)",
                )
            }
        }
    }

    /** Приветствие о состоянии устройства отправляется только один раз; другой раунд отправляется, когда [force] = true (исправление 0x5703 во время периода ожидания). */
    private var greetingsSent = false

    /**
     * Приветствие о состоянии устройства : идентификатор беспроводного сеанса 0x4E0D / язык 0x4E0A / имя устройства 0x4E09 /
     * 0x4E0B время устройства / UUID устройства 0x4E0C. Должен быть отправлен сразу после 0xAA05.
     */
    private fun sendDeviceStateGreetings(force: Boolean = false) {
        if (greetingsSent && !force) return
        greetingsSent = true
        send(Iap2MessageIds.WIRELESS_CARPLAY_UPDATE, Iap2Csm.u8(0, 1))
        send(Iap2MessageIds.DEVICE_LANGUAGE_UPDATE, Iap2Csm.string(0, "zh-CN"))
        send(Iap2MessageIds.DEVICE_INFORMATION_UPDATE, Iap2Csm.string(0, deviceName))
        val epochSeconds = System.currentTimeMillis() / 1000L
        val timezoneMinutes =
            java.util.TimeZone
                .getDefault()
                .getOffset(System.currentTimeMillis()) / 60_000
        send(
            Iap2MessageIds.DEVICE_TIME_UPDATE,
            Iap2Csm.param(0, u64Bytes(epochSeconds)) +
                Iap2Csm.u16(1, timezoneMinutes and 0xFFFF) +
                Iap2Csm.u8(2, 0),
        )
        send(
            Iap2MessageIds.DEVICE_UUID_UPDATE,
            Iap2Csm.string(0, deviceUuid()),
        )
        log(
            "iap2 tx=0x4e0d/0x4e0a/0x4e09/0x4e0b/0x4e0c приветствие статуса устройства" +
                "（name=$deviceName mac=$bluetoothMac）",
        )
    }

    /** Крайний срок для сегментированного ожидания: возьмите меньшее значение «общий срок» и «миллисекунды ожидания». */
    private fun wifiRescueDeadline(
        deadlineNanos: Long,
        millis: Long,
    ): Long = minOf(deadlineNanos, System.nanoTime() + millis * 1_000_000L)

    private fun send(
        messageId: Int,
        vararg body: ByteArray,
    ) {
        val joined =
            when (body.size) {
                0 -> ByteArray(0)
                1 -> body[0]
                else -> body.reduce { acc, bytes -> acc + bytes }
            }
        val frame = Iap2Csm.encode(messageId, joined)
        val limit = channel.peerMaxControlPayload() ?: (frame.size - 1).coerceAtLeast(1)
        var offset = 0
        while (offset < frame.size) {
            val end = minOf(offset + limit, frame.size)
            if (!channel.sendControl(frame.copyOfRange(offset, end))) {
                throw IOException("Соединение iAP2 не работает при отправке 0x${messageId.toString(16)}")
            }
            offset = end
        }
        log("iap2 tx=0x${messageId.toString(16).padStart(4, '0')}")
    }

    /** Вариант [send] по принципу «отправить и забыть»: ссылка не передает повторно или умирает из-за того, что партнер не подтверждает сообщение (см. 0x4E0E). */
    private fun sendFireAndForget(
        messageId: Int,
        body: ByteArray,
    ) {
        val frame = Iap2Csm.encode(messageId, body)
        val limit = channel.peerMaxControlPayload() ?: (frame.size - 1).coerceAtLeast(1)
        var offset = 0
        while (offset < frame.size) {
            val end = minOf(offset + limit, frame.size)
            if (!channel.sendControl(frame.copyOfRange(offset, end), awaitAck = false)) {
                throw IOException("Соединение iAP2 не работает при отправке 0x${messageId.toString(16)}")
            }
            offset = end
        }
        log("iap2 tx=0x${messageId.toString(16).padStart(4, '0')} (отправить и забыть)")
    }

    private fun expect(
        messageId: Int,
        deadline: Long,
    ): Iap2Csm.Frame =
        expectOrNull(messageId, deadline)
            ?: throw IOException("Ожидание таймаута 0x${messageId.toString(16)}")

    /**
     * То же, что [expect], но возвращает ноль по тайм-ауту (для дополнительных сообщений). Неожиданные кадры
     * помещаются во временное хранилище для последующего использования.
     *
     * считывает только новые кадры из [receivedFrames], **не перечитывает только что временно сохраненные кадры**:
     * старая реализация использует один из них
     * , неожиданные кадры помещаются обратно и немедленно удаляются этой функцией, образуя живую блокировку (см.
     * комментарий pendingFrames).
     * Если целевой кадр       уже находится во временной области хранения (раннее поступление), сначала извлеките
     * его отсюда, чтобы исключить утечку.
     */
    private fun expectOrNull(
        messageId: Int,
        deadlineNanos: Long,
    ): Iap2Csm.Frame? {
        pendingFrames.firstOrNull { it.messageId == messageId }?.let {
            pendingFrames.remove(it)
            return it
        }
        while (true) {
            val remaining = (deadlineNanos - System.nanoTime()) / 1_000_000L
            if (remaining <= 0) return null
            val frame = recvNewFrame(remaining)
            if (frame == null) {
                if (!channel.isAlive) return null
                continue
            }
            if (frame.messageId == messageId) return frame
            log(
                "iap2 rx=0x${frame.messageId.toString(16).padStart(4, '0')} " +
                    "(${Iap2MessageIds.nameOf(frame.messageId)}), неожиданно, временно сохраняется для последующего потребления",
            )
            pendingFrames += frame
            if (pendingFrames.size > maxPendingFrames) {
                pendingFrames.removeFirst()
                if (!pendingOverflowLogged) {
                    pendingOverflowLogged = true
                    log(
                        "Область буфера неожиданных кадров iap2 превышает $maxPendingFrames - отбросить самый старый " +
                            "(слишком много сообщений о подписке на машину-машину)",
                    )
                }
            }
        }
    }

    private fun awaitOptionalHid(deadline: Long) {
        // Если в списке объявлений нет StartHID, он не будет ждать (реальные тесты DiPlay/Audi не будут выданы, а старый
        // процесс будет зря ждать 2 секунды для каждого раунда).

        if (accessoryDeclaresSend(Iap2MessageIds.START_HID) == false) {
            log("Машина автомобиля iap2 не заявляет, что отправит 0x6800 StartHID - пропустите 2 секунды и подождите")
            return
        }
        val hidWindowNanos = minOf(System.nanoTime() + HID_WAIT_NANOS, deadline)
        while (true) {
            val remaining = (hidWindowNanos - System.nanoTime()) / 1_000_000L
            if (remaining <= 0) {
                log("iap2 не получил 0x6800 (принимающая сторона не отправляет StartHID, продолжить)")
                return
            }
            val frame = recvFrame(remaining)
            if (frame == null) {
                if (!channel.isAlive) return // Ссылка не работает: оставьте ее для последующих действий, ожидайте сообщения о явной ошибке.
                continue
            }
            when (frame.messageId) {
                Iap2MessageIds.START_HID -> {
                    log("iap2 rx=0x6800 start-hid bytes=${frame.body.size}")
                    send(
                        Iap2MessageIds.DEVICE_HID_REPORT,
                        Iap2Csm.u16(0, 0),
                        Iap2Csm.param(1, byteArrayOf(0)),
                    )
                    return
                }

                else ->
                    log(
                        "iap2 rx=0x${frame.messageId.toString(16).padStart(4, '0')} " +
                            "(${Iap2MessageIds.nameOf(frame.messageId)})",
                    )
            }
        }
    }

    /**
     * Универсальная выборка кадров (запрос MFi/ожидание HID/поддержание активности): установите приоритет
     * использования буферизованных неожиданных кадров.
     * (сохраните порядок поступления: временное хранилище > новый анализ), а затем прочитайте новые кадры.
     */
    private fun recvFrame(timeoutMillis: Long): Iap2Csm.Frame? {
        pendingFrames.firstOrNull()?.let {
            pendingFrames.removeFirst()
            return it
        }
        return recvNewFrame(timeoutMillis)
    }

    /** Получайте только новые кадры (сначала проанализируйте очередь, затем прочитайте сокет); никогда не возвращайте кадры в область временного хранения. */
    private fun recvNewFrame(timeoutMillis: Long): Iap2Csm.Frame? {
        receivedFrames.firstOrNull()?.let {
            receivedFrames.removeFirst()
            return it
        }
        if (timeoutMillis <= 0) return null
        val bytes = channel.recvControl(timeoutMillis) ?: return null
        val frames = parser.offer(bytes)
        if (frames.isEmpty()) return null
        frames.forEachIndexed { index, frame -> if (index > 0) receivedFrames += frame }
        return frames.first()
    }

    // ---- Анализ ----

    /** Учетные данные точки доступа, разобранные из 0x5703 (WiFi+broadcast_carplay-ctrl следует привязать сразу при получении). */
    data class WifiConfiguration(
        val ssid: String,
        val passphrase: String,
        val channel: Int,
        val securityType: Int,
    )

    private fun parseWifiConfiguration(frame: Iap2Csm.Frame): WifiConfiguration {
        val params = Iap2Csm.parseParams(frame.body).associateBy { it.id }
        return WifiConfiguration(
            ssid = params[1]?.value?.asStringOrEmpty() ?: "",
            passphrase = params[2]?.value?.asStringOrEmpty() ?: "",
            securityType =
                params[3]
                    ?.value
                    ?.firstOrNull()
                    ?.toInt()
                    ?.and(0xFF) ?: 0,
            channel =
                params[4]
                    ?.value
                    ?.firstOrNull()
                    ?.toInt()
                    ?.and(0xFF) ?: 0,
        )
    }

    /**
     * анализирует 0x4301. Информация AP поступает из двух источников:
     * — можно получить через 0x5703 (машина по старому соглашению) → использовать напрямую;
     * - Автомобильный блок указан только в беспроводной группе 0x4301 (автомобильный блок с новым протоколом,
     * например BMW iD9) → анализировать из группы.
     *
     * Новая группа беспроводных протоколов       изоморфна AccessoryWiFiConfigurationInformation из приложения CarPlay.
     * (0/1=SSID/пароль, 2=канал, 3=IP, 4=тип безопасности), но отдельные реализации нумеруются с 1 (этот проект 0x5703
     * Анализ       — 1/2/3/4) — оба совместимы: первые две «не-IP» строки с нулевым завершением используются
     * поочередно в качестве SSID/пароля,
     * Однобайтовые поля       классифицируются по диапазону значений. Исходные байты регистрируются каждый раз и
     * могут быть исправлены непосредственно после фактического тестирования реального автомобиля.
     */
    private fun parseStartSession(
        frame: Iap2Csm.Frame,
        wifi: WifiConfiguration?,
    ): CarPlayEndpoint {
        val params = Iap2Csm.parseParams(frame.body).associateBy { it.id }
        val wirelessGroup = params[1]?.value
        val wireless = wirelessGroup?.let { Iap2Csm.parseParams(it) }
        val addresses =
            wireless
                ?.filter { it.id == 3 }
                ?.mapNotNull { param -> param.value.asStringOrEmpty()?.takeIf { it.isNotEmpty() } }
                .orEmpty()
        log(
            "Параметры верхнего уровня iap2 0x4301:" +
                params.entries.joinToString(" ") { (id, param) -> "#$id(${param.value.size}B)" },
        )
        if (wireless != null) {
            log(
                "Параметры беспроводной группы iap2 0x4301:" +
                    wireless.joinToString(" ") { param ->
                        "#${param.id}=" + param.value.joinToString("") { "%02x".format(it) }
                    },
            )
        }
        val fromSession = wireless?.let { parseWirelessAp(it) }
        val ap = wifi ?: fromSession
        if (wifi == null && fromSession != null) {
            log(
                "iap2 0x4301 поставляется с точкой доступа: ssid=${fromSession.ssid} канал=${fromSession.channel}" +
                    "security=${fromSession.securityType} psk=${if (fromSession.passphrase.isEmpty()) "(пустой)" else "***"}",
            )
        }
        return CarPlayEndpoint(
            ssid = ap?.ssid ?: "",
            passphrase = ap?.passphrase ?: "",
            channel = ap?.channel ?: 0,
            securityType = ap?.securityType ?: 0,
            airPlayPort = params[2]?.value?.asU32() ?: 0,
            deviceIdentifier = params[3]?.value?.asStringOrEmpty(),
            publicKey = params[4]?.value?.asStringOrEmpty(),
            sourceVersion = params[5]?.value?.asStringOrEmpty(),
            ipAddresses = addresses,
        )
    }

    /**
     * анализирует информацию о точке доступа из беспроводной группы 0x4301 (единственный источник учетных данных для
     * нового протокольного автомобиля).
     *
     * принимает только строки с завершающим NUL, которые «не похожи на IP-адреса»: первая — это SSID, а вторая — пароль;
     * Однобайтовые поля       классифицируются по диапазону значений (канал 1..196, тип безопасности 0..4),
     * идентификатор приоритета канала=2,
     * Во-вторых, тип между id=4/id=3 не является безопасным типом. Если его невозможно проанализировать, будет
     * возвращено значение null (вызывающая сторона сообщит об ошибке и оставит журнал).
     */
    private fun parseWirelessAp(group: List<Iap2Csm.Param>): WifiConfiguration? {
        val ipv4 = Regex("^\\d{1,3}(\\.\\d{1,3}){3}$")
        val strings =
            group
                .sortedBy { it.id }
                .mapNotNull { param -> param.value.asStringOrEmpty() }
                .filter { it.isNotEmpty() && !ipv4.matches(it) && !it.contains(':') }
        val ssid = strings.getOrNull(0)?.takeIf { it.length <= 32 } ?: return null
        val passphrase = strings.getOrNull(1) ?: ""
        val singles = group.filter { it.value.size == 1 }.associate { it.id to (it.value[0].toInt() and 0xFF) }
        val security =
            singles[4]?.takeIf { it in 0..4 }
                ?: singles[3]?.takeIf { it in 0..4 }
                ?: 0
        val channel =
            singles[2]?.takeIf { it in 1..196 }
                ?: singles[4]?.takeIf { it in 1..196 && it != security }
                ?: singles[3]?.takeIf { it in 1..196 && it != security }
                ?: 0
        return WifiConfiguration(ssid = ssid, passphrase = passphrase, channel = channel, securityType = security)
    }

    /**
     * разрешает протокол EA из компонента ExternalAccessoryProtocol 0x1D01 (группа параметров 11.10.12):
     * Субпараметр       0 = номер протокола (u8), 1 = имя протокола. Сравните DiPlay с той же структурой
     * (u8(0,index)+string(1,name)+u8(2,0)).
     */
    private fun parseEaProtocols(frame: Iap2Csm.Frame): List<Pair<Int, String>> {
        val out = ArrayList<Pair<Int, String>>()
        val params = Iap2Csm.parseParams(frame.body).associateBy { it.id }
        for (groupId in intArrayOf(10, 11, 12)) {
            val value = params[groupId]?.value ?: continue
            val sub = Iap2Csm.parseParams(value).associateBy { it.id }
            val protocolId =
                sub[0]
                    ?.value
                    ?.firstOrNull()
                    ?.toInt()
                    ?.and(0xFF) ?: continue
            val name = sub[1]?.value?.asStringOrEmpty() ?: "?"
            out += protocolId to name
            log("iap2 0x1d01 Компонент советника [$groupId] протокол=$protocolId имя=$name")
        }
        return out
    }

    private fun logIdentification(frame: Iap2Csm.Frame) {
        val params = Iap2Csm.parseParams(frame.body).associateBy { it.id }
        val name = params[0]?.value?.asStringOrEmpty()
        val model = params[1]?.value?.asStringOrEmpty()
        val manufacturer = params[2]?.value?.asStringOrEmpty()
        log("iap2 rx=0x1d01 Идентификационное название автомобиля и машины=$name модель=$model производитель=$manufacturer")
        // Параметр 6/7 = Список идентификаторов сообщений, которые транспортное средство заявляет «оно отправит/может получить».
        // Ссылка 7 (которая принимается) прямо сообщает нам, распознает ли она 0x4300 — ключевое свидетельство для
        // реального устранения неполадок автомобиля.

        val sends = params[6]?.value?.asU16List()
        val receives = params[7]?.value?.asU16List()
        if (sends != null) {
            // Последующие дополнительные сообщения (0x6800/0x4301) могут оцениваться в соответствии с этим списком, чтобы
            // избежать ожидания опустошения фиксированного окна.

            accessorySendIds = sends.toSet()
            log(
                "iap2 0x1d01 Список поставки транспортных средств и машин " +
                    "(${sends.size})=" + sends.joinToString(" ") { "0x%04x".format(it) },
            )
            log(
                "iap2 0x1d01 необязательный оператор сообщения: StartHID(0x6800)=" +
                    (accessoryDeclaresSend(Iap2MessageIds.START_HID)?.let { if (it) "сделаю" else "Не отправлено" } ?: "неизвестно") +
                    " CarPlayStartSession(0x4301)=" +
                    (
                        accessoryDeclaresSend(Iap2MessageIds.CARPLAY_START_SESSION)?.let { if (it) "сделаю" else "Не отправлено" }
                            ?: "неизвестно"
                    ),
            )
        }
        if (receives != null) {
            // Могут ли машина и машина принять 0x5702? Решите, следовать ли старому соглашению — если вы его не принимаете,
            // вам придется перейти 0x4300/0x4301.

            // (BMW iD9 не имеет 0x5702 в списке получения, поэтому старый процесс должен ждать истечения времени 0x5703 в каждом раунде).
            accessoryReceiveIds = receives.toSet()
            receiveListDeclared = true
            log(
                "iap2 0x1d01 список дебиторской задолженности по машинам и машинам " +
                    "(${receives.size})=" + receives.joinToString(" ") { "0x%04x".format(it) },
            )
            // Портрет автомобиля-машины (точка закрытия сигнала): идентичность + двойной список → определение эры/wifiGen в одну строку,
            // По следующему - допустив ошибку, можно отследить, какой сигнал отсюда вас ввел в заблуждение (железное
            // правило: по способностям, а не по бренду)

            val profile =
                ReceiverProfile.classify(
                    ReceiverProfile.Signals(
                        name = name,
                        model = model,
                        manufacturer = manufacturer,
                        sendIds = sends?.toSet(),
                        receiveIds = receives.toSet(),
                    ),
                )
            wifiGen = profile.wifiGen
            linkGeneration =
                ReceiverProfile.linkGenerationOf(
                    ReceiverProfile.Signals(
                        name = name,
                        model = model,
                        manufacturer = manufacturer,
                        sendIds = sends?.toSet(),
                        receiveIds = receives.toSet(),
                    ),
                )
            log(
                "IAPLINK: определение генерации канала = $linkGeneration (на этапе AirPlay соответствующим образом " +
                    "назначается стратегия маркера)",
            )
            log(ReceiverProfile.describe(profile))
            log(
                "Генерация протокола iap2 0x1d01: Запрос конфигурации WiFi (0x5702)=" +
                    (
                        accessoryDeclaresReceive(Iap2MessageIds.REQUEST_ACCESSORY_WIFI_CONFIGURATION)?.let {
                            if (it) "Коллекционный" else "Не принято"
                        } ?: "неизвестно"
                    ) +
                    " Вернитесь к настройке Wi-Fi (0x5703)=" +
                    (
                        accessoryDeclaresSend(Iap2MessageIds.ACCESSORY_WIFI_CONFIGURATION)?.let {
                            if (it) "сделаю" else "Не отправлено"
                        } ?: "неизвестно"
                    ) +
                    " → этот " +
                    "раунд" +
                    if (profile.wifiGen ==
                        ReceiverProfile.WifiGen.NEW
                    ) {
                        "Не отправлять 0x5702 (ожидание 0x4301)"
                    } else {
                        "Отправьте 0x5702 (даже если список неполный)"
                    },
            )
        }
        log("iap2 0x1d01 оригинальное тело=" + frame.body.joinToString("") { "%02x".format(it) })
    }

    private fun remainingMillis(deadlineNanos: Long): Long {
        val remaining = (deadlineNanos - System.nanoTime()) / 1_000_000L
        return remaining.coerceIn(0, 60_000L)
    }

    private fun u64Bytes(value: Long): ByteArray =
        ByteArray(8) { index ->
            (value ushr (8 * (7 - index))).toByte()
        }

    /** UUID устройства: детерминированно извлекается из MAC-адреса Bluetooth и стабилен во всех сеансах (он идентифицирует устройство в автомобиле). */
    private fun deviceUuid(): String =
        java.util.UUID
            .nameUUIDFromBytes(bluetoothMac.toByteArray())
            .toString()
            .uppercase()

    /**
     * Строка CSM, завершающаяся NUL. **Необходимо удалить все конечные NUL, а не только один**:
     * Фактические измерения Audi MMI 3315 заполняют поле адреса в беспроводной группе до фиксированной длины (IPv6,
     * за которым следуют 22 NUL,
     * IPv4, а затем 4), переход только к одному даст `"10.174.189.1\u0000\u0000\u0000\u0000"`.
     * Строки такого типа, `contains('.')` имеет значение true, а `contains(':')` является ложным, могут передавать все "независимо от того,
     * IPv4", но оставьте это на усмотрение `InetSocketAddress`.
     * `Unable to resolve host "10.174.189.1"` (NUL не виден в журнале и его крайне сложно увидеть)——
     * 18 октября 2026 г. Фактический тест: сопряжение AirPlay прошло успешно благодаря использованию конечной точки
     * обновления mDNS, но порт видеоданных и
     * KeepAlive по-прежнему использует адрес с NUL, оба провалились, и сессия была удалена машиной через 10 секунд.
     */
    private fun ByteArray.asStringOrEmpty(): String? {
        if (isEmpty() || last() != 0.toByte()) return null
        var end = size
        while (end > 0 && this[end - 1] == 0.toByte()) end--
        return copyOf(end).decodeToString()
    }

    private fun ByteArray.asU32(): Int =
        if (size == 4) {
            ((this[0].toInt() and 0xFF) shl 24) or
                ((this[1].toInt() and 0xFF) shl 16) or
                ((this[2].toInt() and 0xFF) shl 8) or
                (this[3].toInt() and 0xFF)
        } else {
            0
        }

    /** См. список сообщений 6/7: последовательность u16 с обратным порядком байтов (используется для идентификации транспортного средства в кадре для объявления возможности приема/передачи). */
    private fun ByteArray.asU16List(): List<Int>? {
        if (size < 2 || size % 2 != 0) return null
        return (0 until size step 2).map {
            ((this[it].toInt() and 0xFF) shl 8) or (this[it + 1].toInt() and 0xFF)
        }
    }
}

/**
 * — это внутренняя конечная точка, когда в этом раунде не получены учетные данные AP; он возвращает ноль
 * (вызывающая сторона сообщает об ошибке), даже не зная SSID.
 *
 * Зачем это нужно: Приглашение ctrl из автомобиля возможно придется ждать более 20 секунд (реальная запись iPhone: доступ к сети
 * приходит через 21 секунду (`StartSessionHost`), а 0x4301 может даже не прийти за весь раунд (0x5702 предоставил учетные данные
 * Автомобильный автомат  ). В этот момент удаление цепочки эквивалентно очистке таймера ожидания на стороне
 * машины, и следующий раунд снова начинается с 0. Просто знайте, какой из них подключить
 * точка доступа, вы должны позволить главному элементу управления продолжать ждать в соответствии с текущей сетью.
 *
 * `airPlayPort = 0` + пустой адрес = «Конечная точка не самодостаточна», мастер должен дождаться приглашения ctrl перед анализом
 * mDNS/шлюз, опоздавший 0x4301 по-прежнему будет обновлять конечную точку в горячем режиме.
 */
internal fun credentiallessEndpoint(cachedSsid: String?): Iap2SenderSession.CarPlayEndpoint? {
    val ssid = cachedSsid?.trim()?.takeIf { it.isNotEmpty() } ?: return null
    return Iap2SenderSession.CarPlayEndpoint(
        ssid = ssid,
        passphrase = "",
        channel = 0,
        securityType = 0,
        airPlayPort = 0,
        deviceIdentifier = null,
        publicKey = null,
        sourceVersion = null,
        ipAddresses = emptyList(),
    )
}
