package io.github.shaonialife.cardeck.render

import android.graphics.Bitmap

/**
 * Карта наложения синтезатора  (в настоящее время используется для подсказки «принудительное горизонтальное
 * положение экрана не вступает в силу»).
 *
 * Растровое изображение   рисуется вызывающей стороной в фоновом потоке (текст, набранный Android Canvas), а
 * поток GL отвечает только за загрузку текстур и
 * чертеж  ; прямоугольник использует **координаты выходного изображения** (та же система координат, что и поток
 * кодирования, начало координат сверху),
 * Таким образом, одно и то же значение можно напрямую использовать повторно для определения касания без
 * необходимости вычислений масштабирования/поворота.
 */
class OverlayCard(
    val bitmap: Bitmap,
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float,
) {
    fun contains(
        x: Float,
        y: Float,
    ): Boolean = x >= left && x < right && y >= top && y < bottom
}
