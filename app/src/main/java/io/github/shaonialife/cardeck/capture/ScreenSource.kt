package io.github.shaonialife.cardeck.capture

import android.view.Surface

/**
 * Абстракция источника изображения «транспортное средство-машина»: входная поверхность кодера заполняется источником изображения.
 * Единственная текущая реализация: [HiddenDisplaySource] (невидимый экран: доверенный виртуальный экран + Шизуку
 * запускает на нем приложение).
 *
 * (исходный «Рабочий стол» (собственно нарисованная презентация) и «Зеркальный главный экран» (MediaProjection AUTO_MIRROR)
 * Оба режима были удалены по требованию 10 октября 2026 г. )
 */
interface ScreenSource {
    val name: String

    /** Привяжите (или перепривяжите) поверхность кодирования; вернитесь, было ли оно успешным */
    fun attach(
        surface: Surface,
        width: Int,
        height: Int,
        densityDpi: Int,
    ): Boolean

    /** Отменить привязку поверхности (сохранить базовые ресурсы для быстрого повторного подключения) */
    fun detach()

    /** Освободить все ресурсы */
    fun release()
}
