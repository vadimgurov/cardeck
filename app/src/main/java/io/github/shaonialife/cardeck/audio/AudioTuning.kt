package io.github.shaonialife.cardeck.audio

/**
 * Параметры инкапсуляции/временной метки полезной нагрузки аудио (**завершено, только установлено**).
 *
 * Информация о  : 20 октября 2026 г. на Honda HFT/Alpine 8A250-30A (Telechips tcc805x Android 10)
 * Когда   переходит к `type=102` + AAC-LC 44100, ответ SETUP автомобиля завершен, `/feedback` в `sampleTime`
 * нажимает 44.1к для перехода в реальном времени и разговор идет стабильно и непрерывно, но звука из динамика
 * нет**. В то время были выделены три группы возможных различий в упаковке.
 * (голый кадр/ADTS, объявленный spf/необъявленный, временная метка прибытия/высокоточная временная метка)
 * превращен в переключаемое решение.
 * по одному тестировался на машине.
 *
 * Окончательный вывод: настоящей основной причиной является не инкапсуляция, а переупорядочение PCM s16 битового
 * потока AAC перед отправкой.
 * (см. `sealPacket` для [AudioSender]). После изменения порядка и его исправления слышна **Схема 1**.
 * Различия между двумя другими группами   не оказывают влияния на данный автомобильный автомат, поэтому они
 * сходятся к единому набору параметров и никакого переключения не предусмотрено.
 */
enum class AudioTuning(
    /** Добавлять ли заголовок ADTS к каждому кадру. */
    val adts: Boolean,
    /** spf (количество образцов кадров на пакет), объявленный в SETUP; ноль = не объявлено. */
    val spf: Int?,
    /** поддерживаетHighAccuracyTimestamps в НАСТРОЙКЕ. */
    val highAccuracyTimestamps: Boolean,
) {
    /** Голый кадр AAC + `spf=1024` + временная метка прибытия — единственная комбинация, доступная для тестирования реального автомобиля. */
    RAW_SPF(
        adts = false,
        spf = 1024,
        highAccuracyTimestamps = false,
    ),
    ;

    /** Однострочное описание журнала. */
    val detail: String
        get() = "Голый кадр AAC + spf=$spf + метка времени прибытия"
}
